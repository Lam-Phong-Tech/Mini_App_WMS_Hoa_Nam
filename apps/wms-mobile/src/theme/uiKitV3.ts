/** Preserve approved photographic gradient opacity while taking RGB only from
 * an official semantic role. Do not use opacity for disabled controls. */
export function uiColorAlpha(role:HnColorRole,opacity:number):string{
  const hex=UI_KIT_COLORS[role].slice(1),alpha=Math.max(0,Math.min(1,opacity));
  const rgb=[0,2,4].map(index=>parseInt(hex.slice(index,index+2),16));
  return `rgba(${rgb.join(',')},${alpha})`;
}
